export type MessageKey = keyof typeof messages

export function resolveMessage(key: MessageKey, language: AppLanguage): string {
  const descriptor = messages[key]
  return descriptor[language]
}

export function translateMessage(
  key: MessageKey,
  language: AppLanguage,
  params?: Record<string, string | number>,
): string {
  const template = resolveMessage(key, language)

  if (!params) {
    return template
  }

  return template.replace(/\{\{\s*([^{}\s]+)\s*\}\}/g, (_, paramKey: string) => {
    if (!(paramKey in params)) {
      return ''
    }

    return `${params[paramKey]}`
  })
}
